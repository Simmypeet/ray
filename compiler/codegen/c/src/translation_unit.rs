use std::io::{self, Write};

use rayc_qbice::TrackedEngine;
use rayc_symbol::symbol_kind::get_all_def_ids;
use rayc_target::TargetID;

use crate::{
    context::{Context, instantiation::CDef},
    writer::Writer,
};

/// Writes a complete C translation unit for `target_id` to `buf`.
pub async fn write_c_translation_unit(
    engine: &TrackedEngine,
    target_id: TargetID,
    buf: &mut impl Write,
) -> io::Result<()> {
    let mut generator = Context::new(engine.clone());
    let def_ids = engine.get_all_def_ids(target_id).await;

    for def_id in def_ids.iter().copied() {
        let cdef = CDef::builder().def_id(target_id.make_global(def_id)).build();
        let _ = generator.get_cdef_id(cdef).await;
    }

    let cdef_ids = generator.cdef_decl_ids().collect::<Vec<_>>();
    let mut function_definitions = Vec::with_capacity(cdef_ids.len());

    for cdef_id in cdef_ids {
        let mut definition = Vec::new();
        let mut writer = Writer::new(&mut definition);
        writer.generate_function_definition(cdef_id, &mut generator).await?;
        function_definitions.push(definition);
    }

    writeln!(buf, "/* This file is auto generated by Ray compiler */")?;
    writeln!(buf, "#include <stdint.h>")?;
    writeln!(buf, "#include <stdbool.h>")?;

    writeln!(buf)?;
    writeln!(buf, "/* Composite type forward declarations */")?;

    generator.write_forward_decl_tuples(buf)?;

    writeln!(buf)?;
    writeln!(buf, "/* Composite type definitions */")?;

    generator.write_tuple_struct_defs(buf)?;

    writeln!(buf)?;
    writeln!(buf, "/* Function forward declarations */")?;

    generator.write_forward_decl_cdefs(buf).await?;

    writeln!(buf)?;
    writeln!(buf, "/* Function definitions */")?;

    for definition in function_definitions {
        buf.write_all(&definition)?;
        writeln!(buf)?;
        writeln!(buf)?;
    }

    Ok(())
}

#[cfg(test)]
mod test {
    use std::{collections::HashMap, sync::Arc};

    use qbice::{
        serialize::Plugin, stable_hash::SeededStableHasherBuilder, storage::intern::Interned,
    };
    use rayc_arena::ID;
    use rayc_ir::{
        cfg::Terminator,
        expression::{Expression, ExpressionKind, call::Call, literal::Literal, tuple::Tuple},
        function::Function,
    };
    use rayc_lexical::tree::{Branch, OffsetMode, RelativeLocation, RelativeSpan};
    use rayc_qbice::{Engine, InMemoryFactory, PrecomputedExecutor, TrackedEngine};
    use rayc_semantic_element::{parameter::ParameterMap, return_type};
    use rayc_source_file::LocalSourceID;
    use rayc_symbol::{SymbolID, name, symbol_kind::AllDefIDs};
    use rayc_type::ty::{Primitive, Ty};

    use super::*;

    fn span() -> RelativeSpan {
        let location = RelativeLocation {
            offset: 0,
            mode: OffsetMode::Start,
            relative_to: ID::<Branch>::new(0),
        };
        RelativeSpan::new(location, location, TargetID::TEST.make_global(LocalSourceID::new(0, 0)))
    }

    fn push_expression(
        function: &mut Function,
        kind: ExpressionKind,
        ty: Interned<Ty>,
    ) -> rayc_ir::expression::ExpressionID {
        let expression = function.insert_expression(Expression::new(kind, span(), ty));
        function.push_expression(function.entry_block(), expression);
        expression
    }

    async fn setup_engine(
        definitions: Vec<(SymbolID, &str, Function, Interned<Ty>)>,
    ) -> TrackedEngine {
        let interner = rayc_qbice::create_minimal_engine().await;
        let definition_ids: Arc<[SymbolID]> =
            definitions.iter().map(|(id, _, _, _)| *id).collect::<Vec<_>>().into();
        let empty_parameters = interner.intern(ParameterMap::new());
        let names = definitions
            .iter()
            .map(|(id, value, _, _)| {
                (
                    name::Key { symbol_id: TargetID::TEST.make_global(*id) },
                    interner.intern_unsized((*value).to_owned()),
                )
            })
            .collect();
        let return_types = definitions
            .iter()
            .map(|(id, _, _, ty)| {
                (return_type::Key { symbol_id: TargetID::TEST.make_global(*id) }, ty.clone())
            })
            .collect();
        let parameter_maps = definitions
            .iter()
            .map(|(id, _, _, _)| {
                (
                    rayc_semantic_element::parameter::Key {
                        symbol_id: TargetID::TEST.make_global(*id),
                    },
                    empty_parameters.clone(),
                )
            })
            .collect();
        let functions = definitions
            .into_iter()
            .map(|(id, _, function, _)| {
                (rayc_ir::Key { def_id: TargetID::TEST.make_global(id) }, interner.intern(function))
            })
            .collect();

        let mut engine =
            Engine::new_with(Plugin::default(), InMemoryFactory, SeededStableHasherBuilder::new(0))
                .await
                .unwrap();
        engine.register_executor(Arc::new(PrecomputedExecutor::new(HashMap::from([(
            AllDefIDs { target: TargetID::TEST },
            definition_ids,
        )]))));
        engine.register_executor(Arc::new(PrecomputedExecutor::new(names)));
        engine.register_executor(Arc::new(PrecomputedExecutor::new(return_types)));
        engine.register_executor(Arc::new(PrecomputedExecutor::new(parameter_maps)));
        engine.register_executor(Arc::new(PrecomputedExecutor::new(functions)));
        Arc::new(engine).tracked().await
    }

    async fn render(engine: &TrackedEngine) -> String {
        let mut output = Vec::new();
        write_c_translation_unit(engine, TargetID::TEST, &mut output).await.unwrap();
        String::from_utf8(output).unwrap()
    }

    #[tokio::test]
    async fn translation_unit_emits_multiple_ir_functions_and_call() {
        let interner = rayc_qbice::create_minimal_engine().await;
        let int32 = Ty::new_primitive(Primitive::Int32, &interner);
        let producer_id = SymbolID::from_u128(0);
        let consumer_id = SymbolID::from_u128(1);
        let producer_global = TargetID::TEST.make_global(producer_id);

        let mut producer_function = Function::new();
        let value = push_expression(
            &mut producer_function,
            ExpressionKind::Literal(Literal::Numeric(7)),
            int32.clone(),
        );
        producer_function
            .set_terminator(producer_function.entry_block(), Terminator::Return(Some(value)));

        let mut consumer_function = Function::new();
        let call = push_expression(
            &mut consumer_function,
            ExpressionKind::Call(Call::new(producer_global, Vec::new())),
            int32.clone(),
        );
        consumer_function
            .set_terminator(consumer_function.entry_block(), Terminator::Return(Some(call)));

        let engine = setup_engine(vec![
            (producer_id, "callee", producer_function, int32.clone()),
            (consumer_id, "caller", consumer_function, int32),
        ])
        .await;
        let output = render(&engine).await;

        assert_eq!(output.matches("int32_t ray_callee(void)").count(), 2);
        assert_eq!(output.matches("int32_t ray_caller(void)").count(), 2);
        assert_eq!(output.matches("ray_callee()").count(), 1);
        assert!(
            output.contains("ray_block_0:\n    ray_expr_0 = ray_callee();\n    return ray_expr_0;")
        );
    }

    #[tokio::test]
    async fn body_only_tuple_is_declared_before_function_definitions() {
        let interner = rayc_qbice::create_minimal_engine().await;
        let int32 = Ty::new_primitive(Primitive::Int32, &interner);
        let pair_ty =
            Ty::new_tuple(interner.intern_unsized([int32.clone(), int32.clone()]), &interner);
        let def_id = SymbolID::from_u128(0);
        let mut function = Function::new();
        let first = push_expression(
            &mut function,
            ExpressionKind::Literal(Literal::Numeric(1)),
            int32.clone(),
        );
        let second = push_expression(
            &mut function,
            ExpressionKind::Literal(Literal::Numeric(2)),
            int32.clone(),
        );
        let pair = push_expression(
            &mut function,
            ExpressionKind::Tuple(Tuple::new(vec![first, second])),
            pair_ty,
        );
        function.set_terminator(function.entry_block(), Terminator::Return(Some(first)));

        let engine = setup_engine(vec![(def_id, "tuple_body", function, int32)]).await;
        let output = render(&engine).await;
        let typedef_start = output.find("typedef struct RayTuple_").unwrap();
        let typedef_end = output[typedef_start..].find(';').unwrap() + typedef_start;
        let typedef = &output[typedef_start..=typedef_end];
        let tuple_name = typedef.split_whitespace().nth(3).unwrap().trim_end_matches(';');
        let struct_start = output.find("\nstruct RayTuple_").unwrap();
        let function_start = output.find("int32_t ray_tuple_body(void) {").unwrap();

        assert!(typedef_start < struct_start);
        assert!(struct_start < function_start);
        assert!(output[function_start..].contains(&format!("{tuple_name} ray_expr_2;")));
        assert!(output[function_start..].contains(&format!(
            "ray_expr_2 = (({tuple_name}){{.elem0 = ray_expr_0,.elem1 = ray_expr_1}});"
        )));

        let _ = pair;
    }
}
