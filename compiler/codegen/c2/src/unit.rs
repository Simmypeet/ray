//! The sections of a generated C translation unit.

use std::fmt::{self, Display, Write as _};

use crate::{
    aggregates::AggregateRegistry,
    c::{aggregate::AggregateDefinition, name::BodyName},
};

/// The includes, and the runtime functions the generated code calls.
///
/// The runtime is defined in a translation unit of its own (see
/// [`write_c_runtime`]), so that the headers it includes never meet the
/// declarations of this unit. A Ray program may declare any C function as an
/// `extern def`, with its own spelling of the types, such as `srand(int)`, and
/// that declaration would conflict with the header's.
///
/// [`write_c_runtime`]: crate::write_c_runtime
const PRELUDE: &str = "\
/* This file is auto generated by the Ray compiler. */
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <math.h>

/* Ray runtime, defined in its own translation unit */
void *ray_alloc(size_t size);
void ray_free(void *pointer);

";

const WRITE_TO_STRING: &str = "writing to a String cannot fail";

/// A generated C translation unit.
///
/// Function definitions are appended as functions are processed; aggregate
/// definitions are added once every aggregate is known, since their order
/// depends on the complete set. The unit renders through [`Display`].
#[derive(Debug, Default)]
pub(crate) struct TranslationUnit {
    aggregate_declarations: String,
    aggregate_definitions: String,
    function_declarations: String,
    function_definitions: String,
}

impl TranslationUnit {
    /// Adds a forward declaration, written without its trailing `;`.
    ///
    /// Every function is declared once, in the order it is generated; the
    /// order is deterministic because the function worklist is.
    pub(crate) fn declare_function(&mut self, declaration: impl Display) {
        writeln!(self.function_declarations, "{declaration};").expect(WRITE_TO_STRING);
    }

    /// Adds a function definition.
    pub(crate) fn define_function(&mut self, definition: &str) {
        start_definition(&mut self.function_definitions);
        self.function_definitions.push_str(definition);
        self.function_definitions.push('\n');
    }

    /// Adds a `main` that runs the given Ray entry point.
    pub(crate) fn define_entry_point(&mut self, entry_point: BodyName) {
        start_definition(&mut self.function_definitions);
        writeln!(self.function_definitions, "int main(void) {{ return {entry_point}(); }}")
            .expect(WRITE_TO_STRING);
    }

    /// Adds every aggregate of `registry`, each after the aggregates it
    /// contains by value.
    pub(crate) fn define_aggregates(&mut self, registry: &AggregateRegistry) {
        for (name, aggregate, layout) in registry.in_definition_order() {
            writeln!(self.aggregate_declarations, "typedef struct {name} {};", name.typedef())
                .expect(WRITE_TO_STRING);
            let definition = AggregateDefinition::new(aggregate, layout);
            start_definition(&mut self.aggregate_definitions);
            writeln!(self.aggregate_definitions, "{definition}").expect(WRITE_TO_STRING);
        }
    }
}

impl Display for TranslationUnit {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(PRELUDE)?;
        let sections = [
            ("Aggregate type forward declarations", &self.aggregate_declarations),
            ("Aggregate type definitions", &self.aggregate_definitions),
            ("Function forward declarations", &self.function_declarations),
            ("Function definitions", &self.function_definitions),
        ];
        for (heading, contents) in sections {
            // Contents are newline-terminated lines, so a blank line follows.
            write!(formatter, "/* {heading} */\n{contents}\n")?;
        }
        Ok(())
    }
}

/// Separates a definition from the previous one with a blank line.
fn start_definition(buffer: &mut String) {
    if !buffer.is_empty() {
        buffer.push('\n');
    }
}
